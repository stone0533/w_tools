import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:w_tools_cli/src/context/context_project.dart';

Directory _project({String toolkitVersion = '1.0.0', String lockCliVersion = '1.0.0'}) {
  final root = Directory.systemTemp.createTempSync('wt_snap_');
  File(p.join(root.path, 'pubspec.yaml')).writeAsStringSync(
    "name: demo_app\n"
    "environment:\n  sdk: ^3.10.0\n"
    "dependencies:\n"
    "  w_tools_ui: ^1.1.0\n"
    "  w_tools_core: ^1.0.1\n"
    "dev_dependencies:\n"
    "  w_tools_cli: ^1.0.0\n",
  );
  File(p.join(root.path, 'pubspec.lock')).writeAsStringSync(
    'packages:\n'
    '  w_tools_ui:\n    version: "1.1.0"\n'
    '  w_tools_core:\n    version: "1.0.1"\n'
    '  w_tools_cli:\n    version: "$lockCliVersion"\n',
  );
  final toolkit = File(p.join(root.path, 'lib', 'app', 'w', 'toolkit.dart'));
  toolkit.parent.createSync(recursive: true);
  toolkit.writeAsStringSync(
    '// generated by w_tools_cli $toolkitVersion\n'
    "export 'package:w_tools_ui/w_tools_ui.dart';\n"
    "export 'package:w_tools_core/w_tools_core.dart';\n",
  );
  final staged = File(p.join(root.path, 'lib', 'app', 'design_system', 'x.dart'));
  staged.parent.createSync(recursive: true);
  staged.writeAsStringSync('// STAGED: 待上移\nclass X {}\n');
  return root;
}

void main() {
  test('快照包含版本、toolkit、暂存层与检查结果', () {
    final root = _project();
    final snap = ProjectSnapshot.load(root);
    expect(snap.projectName, 'demo_app');
    expect(snap.packages['w_tools_ui'], '1.1.0');
    expect(snap.dependencies, ['w_tools_core', 'w_tools_ui']);
    expect(snap.toolkitExports, ['w_tools_core', 'w_tools_ui']);
    expect(snap.designSystemFiles, 1);
    expect(snap.missingStaged, 0);
    expect(snap.errorCount, 0);

    final json = snap.toJson();
    expect(json['schemaVersion'], 1);
    expect(json['catalogVersion'], isPositive);
    expect((json['project'] as Map)['name'], 'demo_app');
    expect((json['doctor'] as Map)['error'], 0);
    expect(json['commands'], isA<Map>());
  });

  test('markdown / prompt 都能生成，prompt 支持截断', () {
    final snap = ProjectSnapshot.load(_project());
    expect(snap.toMarkdown(), contains('# w_tools 项目上下文'));
    expect(snap.toMarkdown(), contains('w_tools_ui'));
    final prompt = snap.toPrompt();
    expect(prompt, contains('项目: demo_app'));
    final short = snap.toPrompt(maxTokens: 6);
    expect(short.length, lessThan(prompt.length));
    expect(short, contains('已截断'));
  });
}
